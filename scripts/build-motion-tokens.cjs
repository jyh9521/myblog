const fs=require('node:fs');
const path=require('node:path');
const ts=require('typescript');
const m={exports:{}};
new Function('exports','module',ts.transpile(fs.readFileSync(path.join(__dirname,'../lib/motion.ts'),'utf8'),{module:ts.ModuleKind.CommonJS}))(m.exports,m);
const {motion,springFrames}=m.exports;
const lines=['/* Generated by scripts/build-motion-tokens.cjs from lib/motion.ts. */',':root {'];
for(const [kind,variants] of Object.entries({spatial:motion.spatial,effects:motion.effects}))for(const [name,spring] of Object.entries(variants)){
  lines.push(`  --motion-${kind}-${name}-stiffness: ${spring.stiffness};`,`  --motion-${kind}-${name}-damping: ${spring.damping};`,`  --motion-${kind}-${name}: linear(${springFrames(spring).map(x=>+x.toFixed(5)).join(',')});`);
}
for(const [name,value] of Object.entries(motion.duration))lines.push(`  --motion-duration-${name}: ${value}ms;`);
for(const [name,value] of Object.entries(motion.easing))lines.push(`  --motion-ease-${name}: ${value};`);
lines.push(`  --motion-stagger: ${motion.stagger.step}ms;`,`  --motion-stagger-max: ${motion.stagger.max}ms;`,'  --motion-spring-duration: 600ms;','  --m3-spring: var(--motion-spatial-fast);','}', '');
const output=lines.join('\n'),target=path.join(__dirname,'../app/motion-tokens.css');
if(process.argv.includes('--check')){if(fs.readFileSync(target,'utf8')!==output)throw Error('Motion tokens are stale');console.log('Motion tokens match the physical model');}else{fs.writeFileSync(target,output);console.log('Generated motion tokens');}
